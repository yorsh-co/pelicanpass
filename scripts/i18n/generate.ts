/**
 * Generates everything under src/i18n/generated from the message catalogs,
 * without writing it. `build.ts` writes the result; `check.ts` compares it with
 * what is committed.
 *
 * For each namespace with a pt-BR catalog:
 *   - `formatjs compile --ast` validates the ICU syntax and precompiles the
 *     catalog for every locale: pt-BR itself, the `en-XA` pseudo-locale, and
 *     any translation under messages/<locale>/.
 *   - The pt-BR AST is walked for each message's arguments, and
 *     `<ns>.messages.ts` is emitted with one typed accessor per message.
 * Then `registry.ts` ties every namespace's factory to its catalogs.
 *
 * Output is committed: the server runs .ts sources directly, with no build
 * step, and needs the accessors as much as the browser does. Generated code is
 * limited to erasable TypeScript syntax for the same reason.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import {
  isArgumentElement,
  isDateElement,
  isNumberElement,
  isPluralElement,
  isSelectElement,
  isStructurallySame,
  isTagElement,
  isTimeElement,
} from '@formatjs/icu-messageformat-parser';
import * as prettier from 'prettier';

import {
  BASE_LOCALE,
  DRAFT_LOCALES,
  LOCALES,
  PSEUDO_LOCALE,
} from '../../src/i18n/locales.ts';
import { NAMESPACES } from '../../src/i18n/namespaces.ts';

import type { MessageFormatElement } from '@formatjs/icu-messageformat-parser';

import type { Locale } from '../../src/i18n/locales.ts';
import type { Namespace } from '../../src/i18n/namespaces.ts';

export const ROOT = fileURLToPath(new URL('../../', import.meta.url));
export const GENERATED_DIR = `${ROOT}src/i18n/generated`;
export const MESSAGES_DIR = `${ROOT}src/i18n/messages`;
export const FORMATJS_BIN = `${ROOT}node_modules/.bin/formatjs`;

type Compiled = Record<string, MessageFormatElement[]>;

export interface SourceMessage {
  defaultMessage: string;
  description: string;
}

export type ArgumentType = 'number' | 'string' | 'Date' | { cases: string[] };

const HEADER = (source: string): string =>
  `// Generated by scripts/i18n/build.ts from ${source}. Do not edit.\n\n`;

/**
 * Collects every argument a message takes, including those nested inside
 * plural and select branches.
 *
 * @param elements - The compiled message.
 * @param id - The message ID, for error messages.
 * @param args - Accumulator, keyed by argument name.
 * @throws {Error} On a tag element, or an argument used with two types.
 */
export function collectArguments(
  elements: MessageFormatElement[],
  id: string,
  args = new Map<string, ArgumentType>(),
): Map<string, ArgumentType> {
  const add = (name: string, type: ArgumentType): void => {
    const existing = args.get(name);

    if (
      existing !== undefined &&
      JSON.stringify(existing) !== JSON.stringify(type)
    ) {
      throw new Error(`${id}: argument "${name}" is used with two types`);
    }

    args.set(name, type);
  };

  for (const element of elements) {
    // Tags would make formatting return an array rather than a string, which
    // every accessor promises.
    if (isTagElement(element)) {
      throw new Error(`${id}: tags are not supported (<${element.value}>)`);
    }

    if (isPluralElement(element) || isNumberElement(element)) {
      add(element.value, 'number');
    } else if (isDateElement(element) || isTimeElement(element)) {
      add(element.value, 'Date');
    } else if (isSelectElement(element)) {
      // ICU requires an `other` branch, but it is a fallback for values the
      // caller should not send, so it is not part of the argument's type.
      const cases = Object.keys(element.options)
        .filter((key) => key !== 'other')
        .sort();

      add(element.value, cases.length > 0 ? { cases } : 'string');
    } else if (isArgumentElement(element)) {
      add(element.value, 'string');
    }

    if (isPluralElement(element) || isSelectElement(element)) {
      for (const option of Object.values(element.options)) {
        collectArguments(option.value, id, args);
      }
    }
  }

  return args;
}

const capitalize = (word: string): string =>
  word.charAt(0).toUpperCase() + word.slice(1);

/**
 * Derives an accessor name from a message ID: the namespace prefix is dropped
 * and the remaining segments are camel-cased (`staff.band.retry` → `bandRetry`).
 *
 * @throws {Error} If the ID is outside the namespace or yields an invalid name.
 */
function accessorName(ns: Namespace, id: string): string {
  if (!id.startsWith(`${ns}.`)) {
    throw new Error(`${id}: ID must start with "${ns}."`);
  }

  const name = id
    .slice(ns.length + 1)
    .split('.')
    .map((segment, index) => (index === 0 ? segment : capitalize(segment)))
    .join('');

  if (!/^[a-z][A-Za-z0-9]*$/.test(name)) {
    throw new Error(`${id}: "${name}" is not a valid accessor name`);
  }

  return name;
}

const pascalCase = (ns: string): string =>
  ns.split('-').map(capitalize).join('');

const renderType = (type: ArgumentType): string =>
  typeof type === 'string'
    ? type
    : type.cases.map((value) => JSON.stringify(value)).join(' | ');

const jsDoc = (text: string): string =>
  `/** ${text.replaceAll('*/', '*\\/')} */`;

/**
 * Emits the accessor factory for one namespace.
 *
 * @param ns - The namespace.
 * @param source - The pt-BR catalog, for descriptions.
 * @param compiled - The compiled pt-BR catalog, for argument types.
 */
function renderAccessors(
  ns: Namespace,
  source: Record<string, SourceMessage>,
  compiled: Compiled,
): string {
  const type = pascalCase(ns);
  const ids = Object.keys(compiled).sort();

  const accessors = ids.map((id) => {
    const args = [...collectArguments(compiled[id] ?? [], id)].sort(
      ([a], [b]) => a.localeCompare(b),
    );
    const doc = jsDoc(source[id]?.description ?? '');
    const name = accessorName(ns, id);

    if (args.length === 0) {
      return `${doc}\n${name}: (): string => format(${JSON.stringify(id)}),`;
    }

    const values = args
      .map(([arg, argType]) => `${arg}: ${renderType(argType)}`)
      .join('; ');

    return `${doc}\n${name}: (values: { ${values} }): string => format(${JSON.stringify(id)}, values),`;
  });

  return `${HEADER(`src/i18n/messages/${BASE_LOCALE}/${ns}.json`)}
import { IntlMessageFormat } from 'intl-messageformat';

import type { MessageFormatElement } from '@formatjs/icu-messageformat-parser';
import type { PrimitiveType } from 'intl-messageformat';

import type { Locale } from '../locales.ts';

export type ${type}MessageId =
  ${ids.map((id) => JSON.stringify(id)).join(' | ')};

export type ${type}Catalog = Record<${type}MessageId, MessageFormatElement[]>;

/**
 * Typed accessors for the \`${ns}\` namespace.
 *
 * @param locale - The locale the catalog was compiled for.
 * @param catalog - A compiled \`${ns}\` catalog.
 */
export const create${type}Messages = (locale: Locale, catalog: ${type}Catalog) => {
  const cache = new Map<${type}MessageId, IntlMessageFormat>();

  const format = (
    id: ${type}MessageId,
    values?: Record<string, PrimitiveType>,
  ): string => {
    let message = cache.get(id);

    if (!message) {
      message = new IntlMessageFormat(catalog[id], locale);
      cache.set(id, message);
    }

    // The build rejects tags, so formatting always yields a single string.
    return message.format<string>(values) as string;
  };

  return {
    ${accessors.join('\n\n')}
  };
};

export type ${type}Messages = ReturnType<typeof create${type}Messages>;
`;
}

/**
 * Emits the compiled catalog as a module, so the server can import it under
 * type stripping and the route can inline it.
 */
function renderCatalog(
  ns: Namespace,
  compiled: Compiled,
  sourceFile: string,
): string {
  const type = pascalCase(ns);

  return `${HEADER(sourceFile)}
import type { ${type}Catalog } from '../${ns}.messages.ts';

const catalog: ${type}Catalog = ${JSON.stringify(compiled)};

export default catalog;
`;
}

/**
 * Runs `formatjs compile --ast` on one catalog.
 *
 * @param path - The catalog file.
 * @param pseudoLocale - Emit this pseudo-locale instead of the text as written.
 * @throws {Error} If the catalog holds invalid ICU.
 */
function compile(path: string, pseudoLocale?: Locale): Compiled {
  const args = ['compile', path, '--ast'];

  if (pseudoLocale) args.push('--pseudo-locale', pseudoLocale);

  return JSON.parse(
    execFileSync(FORMATJS_BIN, args, { encoding: 'utf8', stdio: 'pipe' }),
  ) as Compiled;
}

export const readCatalog = async (
  path: string,
): Promise<Record<string, SourceMessage>> =>
  JSON.parse(await readFile(path, 'utf8')) as Record<string, SourceMessage>;

/** A JavaScript identifier from a namespace and locale: `admin-shell`, `pt-BR` → `adminShellPtBR`. */
const identifier = (...parts: string[]): string => {
  const name = parts
    .flatMap((part) => part.split('-'))
    .map(capitalize)
    .join('');

  return name.charAt(0).toLowerCase() + name.slice(1);
};

/**
 * Compiles one translation, filling messages it lacks from the source and
 * rejecting messages whose arguments differ from the source's.
 *
 * A missing message is a warning for a draft locale and an error for one that
 * production offers: a published locale is complete or it is not published.
 */
function compileTranslation(
  ns: Namespace,
  locale: Locale,
  source: Compiled,
  result: GenerateResult,
): Compiled {
  const path = `${MESSAGES_DIR}/${locale}/${ns}.json`;
  const missing = DRAFT_LOCALES.includes(locale)
    ? result.warnings
    : result.errors;

  if (!existsSync(path)) {
    missing.push(`${locale}/${ns}: no translation, serving ${BASE_LOCALE}`);
    return source;
  }

  const translated = compile(path);
  const catalog: Compiled = {};

  for (const id of Object.keys(translated)) {
    if (!(id in source)) {
      result.errors.push(
        `${locale}/${ns}: ${id} is not in the ${BASE_LOCALE} catalog`,
      );
    }
  }

  for (const [id, elements] of Object.entries(source)) {
    const translation = translated[id];

    if (!translation) {
      missing.push(
        `${locale}/${ns}: ${id} is untranslated, serving ${BASE_LOCALE}`,
      );
      catalog[id] = elements;
      continue;
    }

    const same = isStructurallySame(elements, translation);

    if (!same.success) {
      result.errors.push(
        `${locale}/${ns}: ${id}: ${same.error?.message ?? 'arguments differ'}`,
      );
    }

    catalog[id] = translation;
  }

  return catalog;
}

/** Emits the registry that maps each namespace to its factory and catalogs. */
function renderRegistry(namespaces: readonly Namespace[]): string {
  const imports = namespaces.flatMap((ns) => [
    `import { create${pascalCase(ns)}Messages } from './${ns}.messages.ts';`,
    ...LOCALES.map(
      (locale) =>
        `import ${identifier(ns, locale)} from './${locale}/${ns}.ts';`,
    ),
  ]);

  const typeImports = namespaces.map(
    (ns) =>
      `import type { ${pascalCase(ns)}Catalog, ${pascalCase(ns)}Messages } from './${ns}.messages.ts';`,
  );

  const catalogs = namespaces.map(
    (
      ns,
    ) => `const ${identifier(ns)}Catalogs: Record<Locale, ${pascalCase(ns)}Catalog> = {
  ${LOCALES.map((locale) => `'${locale}': ${identifier(ns, locale)},`).join('\n')}
};`,
  );

  return `${HEADER('src/i18n/messages')}
${imports.join('\n')}

import type { Locale } from '../locales.ts';
${typeImports.join('\n')}

${catalogs.join('\n\n')}

/** Every namespace with a catalog, and the accessor object it produces. */
export interface MessagesOf {
  ${namespaces.map((ns) => `'${ns}': ${pascalCase(ns)}Messages;`).join('\n')}
}

export type RegisteredNamespace = keyof MessagesOf;

export const MESSAGES: {
  [N in RegisteredNamespace]: (locale: Locale) => MessagesOf[N];
} = {
  ${namespaces
    .map(
      (ns) =>
        `'${ns}': (locale) => create${pascalCase(ns)}Messages(locale, ${identifier(ns)}Catalogs[locale]),`,
    )
    .join('\n')}
};

export const CATALOGS: Record<RegisteredNamespace, Record<Locale, object>> = {
  ${namespaces.map((ns) => `'${ns}': ${identifier(ns)}Catalogs,`).join('\n')}
};
`;
}

export interface GenerateResult {
  /** Generated file contents, keyed by absolute path. */
  files: Map<string, string>;
  /** Accessor names per namespace, for checking templates. */
  accessors: Map<Namespace, Set<string>>;
  errors: string[];
  warnings: string[];
}

/**
 * Generates every file under src/i18n/generated.
 *
 * Problems are collected rather than thrown, so a check can report all of
 * them at once. A catalog that does not compile is reported and skipped.
 */
export async function generate(): Promise<GenerateResult> {
  const result: GenerateResult = {
    files: new Map(),
    accessors: new Map(),
    errors: [],
    warnings: [],
  };
  const sources: [string, string][] = [];

  for (const dir of readdirSync(MESSAGES_DIR)) {
    if (
      !(LOCALES as readonly string[]).includes(dir) ||
      dir === PSEUDO_LOCALE
    ) {
      result.errors.push(
        `messages/${dir}: not a locale in src/i18n/locales.ts`,
      );
    }
  }

  const registered: Namespace[] = [];

  for (const { name: ns, translatable } of NAMESPACES) {
    const sourcePath = `${MESSAGES_DIR}/${BASE_LOCALE}/${ns}.json`;

    if (!existsSync(sourcePath)) continue;

    try {
      const source = await readCatalog(sourcePath);

      for (const [id, message] of Object.entries(source)) {
        if (!message.description.trim()) {
          result.errors.push(
            `${BASE_LOCALE}/${ns}: ${id} has an empty description`,
          );
        }
      }

      const compiled = compile(sourcePath);

      sources.push([
        `${GENERATED_DIR}/${ns}.messages.ts`,
        renderAccessors(ns, source, compiled),
      ]);
      result.accessors.set(
        ns,
        new Set(Object.keys(compiled).map((id) => accessorName(ns, id))),
      );

      for (const locale of LOCALES) {
        let catalog: Compiled;

        if (locale === BASE_LOCALE) {
          catalog = compiled;
        } else if (locale === PSEUDO_LOCALE) {
          catalog = translatable
            ? compile(sourcePath, PSEUDO_LOCALE)
            : compiled;
        } else if (!translatable) {
          catalog = compiled;
        } else {
          catalog = compileTranslation(ns, locale, compiled, result);
        }

        sources.push([
          `${GENERATED_DIR}/${locale}/${ns}.ts`,
          renderCatalog(
            ns,
            catalog,
            catalog === compiled || locale === PSEUDO_LOCALE
              ? `src/i18n/messages/${BASE_LOCALE}/${ns}.json`
              : `src/i18n/messages/${locale}/${ns}.json`,
          ),
        ]);
      }

      registered.push(ns);
    } catch (err) {
      result.errors.push(
        `${ns}: ${err instanceof Error ? err.message : String(err)}`,
      );
    }
  }

  sources.push([`${GENERATED_DIR}/registry.ts`, renderRegistry(registered)]);

  for (const [path, source] of sources) {
    const config = await prettier.resolveConfig(path);

    result.files.set(
      path,
      await prettier.format(source, { ...config, filepath: path }),
    );
  }

  return result;
}

/** Lists every file currently under src/i18n/generated, as absolute paths. */
export const listGenerated = (): string[] =>
  existsSync(GENERATED_DIR)
    ? readdirSync(GENERATED_DIR, { recursive: true, withFileTypes: true })
        .filter((entry) => entry.isFile())
        .map((entry) => `${entry.parentPath}/${entry.name}`)
        .sort()
    : [];
